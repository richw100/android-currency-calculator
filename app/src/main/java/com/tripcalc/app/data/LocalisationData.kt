fun plugTypeDescription(type: String): String {
    // type may be e.g. "Type C/F" or "Type G" — extract and look up each letter
    val letters = type.removePrefix("Type ").split("/")
    return letters.mapNotNull { PLUG_TYPE_DESCRIPTIONS[it.trim()] }
        .joinToString("\n")
        .ifEmpty { type }
}
